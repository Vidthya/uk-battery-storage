##Prices assumed to be in pounds per MWh

power_mw = 1.0
duration_h = 2.0           ##hours at full power, so energy = power x duration
round_trip_eff = 0.85
annual_degradation = 0.02  ##fraction of capacity lost per year
lifetime_years = 15
discount_rate = 0.07
opex_per_mw_year = 0.0     ##pounds per MW per year; zero means break-even is BEFORE running costs
max_cycles_per_day = 1.0   ##full discharge cycles allowed per day (wear limit)

n_periods = 48             ##half-hours per day
dt = 0.5                   ##hours per half-hour


def solve_day(prices, power, energy, eff):
    """
    Maximise sum(price * dt * (discharge - charge)) over one day.
    Variables: charge (48), discharge (48), state of charge after each period (48).
    Returns the charge and discharge schedules in MW.
    """
    eta = np.sqrt(eff)
    n = n_periods
    ##Objective: to minimise the negative of revenue
    cost = np.concatenate([prices * dt, -prices * dt, np.zeros(n)])

    ##State of charge: s[t] - s[t-1] - dt*eta*charge[t] + dt*discharge[t]/eta = 0
    a_eq = np.zeros((n, 3 * n))
    for t in range(n):
        a_eq[t, 2 * n + t] = 1.0
        if t > 0:
            a_eq[t, 2 * n + t - 1] = -1.0
        a_eq[t, t] = -dt * eta
        a_eq[t, n + t] = dt / eta
    b_eq = np.zeros(n)

    ##Cycle limit: total energy discharged in the day is at most max_cycles x energy capacity
    a_ub = np.zeros((1, 3 * n))
    a_ub[0, n:2 * n] = dt
    b_ub = np.array([max_cycles_per_day * energy])

    bounds = [(0, power)] * n + [(0, power)] * n + [(0, energy)] * n
    res = linprog(cost, A_ub=a_ub, b_ub=b_ub, A_eq=a_eq, b_eq=b_eq, bounds=bounds, method="highs")
    charge, discharge = res.x[:n], res.x[n:2 * n]
    return charge, discharge

def day_revenue(actual_prices, charge, discharge):
    return float(np.sum(actual_prices * dt * (discharge - charge)))


def load_complete_days(path):
    """
    Return a days x 48 table of prices, keeping only days with every half-hour present.
    """
    df = pd.read_csv(path)
    table = df.pivot_table(index="settlementDate", columns="settlementPeriod", values="price")
    table = table.reindex(columns=range(1, n_periods + 1))
    table = table.dropna()
    table.index = pd.to_datetime(table.index)
    return table


def run_dispatch(table, power, duration, eff):
    """
    Daily revenue under perfect foresight and under the 7-day naive forecast.
    """
    energy = power * duration
    days = table.index
    rows = []
    for day in days:
        prev = pd.date_range(day - pd.Timedelta(days=7), day - pd.Timedelta(days=1))
        if not all(d in table.index for d in prev):
            continue
        actual = table.loc[day].values
        forecast = table.loc[prev].values.mean(axis=0)

        c, d = solve_day(actual, power, energy, eff)
        rev_perfect = day_revenue(actual, c, d)

        c, d = solve_day(forecast, power, energy, eff)
        rev_naive = day_revenue(actual, c, d)

        rows.append((day, rev_perfect, rev_naive))
    return pd.DataFrame(rows, columns=["day", "perfect", "naive"]).set_index("day")


def break_even_capex(annual_revenue, power, rate, years, degradation, opex):
    """
    Present value of net cash flows = the most you could pay up front and still break even.
    """
    pv = 0.0
    for t in range(1, years + 1):
        cash = annual_revenue * (1 - degradation) ** (t - 1) - opex * power
        pv += cash / (1 + rate) ** t
    return pv

def main():
    table = load_complete_days("mid_prices.csv")
    table = table[table.index.year <= 2025]
    print(f"Complete days available: {len(table)} ({table.index.min().date()} to {table.index.max().date()})")

    daily = run_dispatch(table, power_mw, duration_h, round_trip_eff)
    print(f"Days used (need 7 complete days before): {len(daily)}")

    ##Annualise: average daily revenue per year x 365; years with gaps are comparable
    by_year = daily.groupby(daily.index.year).agg(["mean", "count"])
    annual = pd.DataFrame({
        "days": by_year["perfect"]["count"],
        "perfect_gbp_per_mw_year": by_year["perfect"]["mean"] * 365 / power_mw,
        "naive_gbp_per_mw_year": by_year["naive"]["mean"] * 365 / power_mw,
    })
    annual["naive_share_of_perfect"] = annual["naive_gbp_per_mw_year"] / annual["perfect_gbp_per_mw_year"]

    for col in ["perfect", "naive"]:
        annual[f"breakeven_capex_{col}_gbp_per_kwh"] = annual[f"{col}_gbp_per_mw_year"].apply(
            lambda r: break_even_capex(r, 1.0, discount_rate, lifetime_years,
                                       annual_degradation, opex_per_mw_year) / (duration_h * 1000))

    ##Neater headings
    annual_out = annual.rename(columns={
        "days": "Days used",
        "perfect_gbp_per_mw_year": "Revenue, perfect foresight (£/MW/year)",
        "naive_gbp_per_mw_year": "Revenue, naive forecast (£/MW/year)",
        "naive_share_of_perfect": "Naive as share of perfect",
        "breakeven_capex_perfect_gbp_per_kwh": "Break-even capex, perfect (£/kWh)",
        "breakeven_capex_naive_gbp_per_kwh": "Break-even capex, naive (£/kWh)",
    })
    annual_out.index.name = "Year"
    print("\nResults by year (placeholder assumptions):")
    print(annual_out.round(2).to_string())
    annual_out.to_csv("results_by_year.csv", encoding="utf-8-sig")

    ##Sensitivity: re-solve for different durations and efficiencies, post-process for the rest
    rows = []
    for dur in [1.0, 2.0, 4.0]:
        for eff in [0.80, 0.85, 0.90]:
            d = run_dispatch(table, power_mw, dur, eff)
            rev_p = d["perfect"].mean() * 365 / power_mw
            rev_n = d["naive"].mean() * 365 / power_mw
            for rate in [0.05, 0.07, 0.10]:
                be_p = break_even_capex(rev_p, 1.0, rate, lifetime_years,
                                        annual_degradation, opex_per_mw_year) / (dur * 1000)
                be_n = break_even_capex(rev_n, 1.0, rate, lifetime_years,
                                        annual_degradation, opex_per_mw_year) / (dur * 1000)
                rows.append((dur, eff, rate, rev_p, rev_n, be_p, be_n))
    sens = pd.DataFrame(rows, columns=["Duration (hours)", "Round-trip efficiency", "Discount rate",
                                       "Revenue, perfect foresight (£/MW/year)", "Revenue, naive forecast (£/MW/year)",
                                       "Break-even capex, perfect (£/kWh)", "Break-even capex, naive (£/kWh)"])
    sens.to_csv("sensitivity.csv", index=False, encoding="utf-8-sig")
    print("\nSensitivity (average over all years):")
    print(sens.round(2).to_string(index=False))

    ##Figure 1: annual revenue, perfect foresight versus naive forecast
    fig, ax = plt.subplots(figsize=(8, 4.5))
    x = np.arange(len(annual_out))
    ax.bar(x - 0.2, annual_out["Revenue, perfect foresight (£/MW/year)"] / 1000, width=0.4, label="Perfect foresight")
    ax.bar(x + 0.2, annual_out["Revenue, naive forecast (£/MW/year)"] / 1000, width=0.4, label="Naive 7-day forecast")
    ax.set_xticks(x); ax.set_xticklabels(annual_out.index)
    ax.set_ylabel("Revenue (£ thousand/MW/year)")
    ax.set_title(f"Annual battery revenue, {duration_h:g}-hour battery, {round_trip_eff:.0%} round-trip efficiency")
    ax.legend(loc="upper left")
    plt.tight_layout()
    plt.savefig("revenue_by_year.png", dpi=150)

    ##Figure 2: break-even capital cost for each price year (perfect foresight)
    fig, ax = plt.subplots(figsize=(8, 4.5))
    ax.bar(x, annual_out["Break-even capex, perfect (£/kWh)"])
    ax.set_xticks(x); ax.set_xticklabels(annual_out.index)
    ax.set_ylabel("£/kWh")
    ax.set_title("Break-even battery cost (£/kWh)")
    plt.tight_layout()
    plt.savefig("breakeven_by_year.png", dpi=150)
    print("\nSaved results_by_year.csv, sensitivity.csv, revenue_by_year.png, breakeven_by_year.png")


if __name__ == "__main__":
    main()

