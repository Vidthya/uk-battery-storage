import os
import time
import requests
import pandas as pd
from concurrent.futures import ThreadPoolExecutor, as_completed

url = "https://data.elexon.co.uk/bmrs/api/v1/datasets/MID"
start = "2019-01-01"
end = "2026-01-01"
out_file = "mid_prices.csv"
cache_dir = "mid_cache"
n_workers = 6

def fetch_window(t_from, t_to, retries=3):
    """
    Request one window of MID data. Returns a list of records.
    Raises ValueError on a 400 so the caller knows the window is too long.
    """
    params = {
        "From": t_from.strftime("%Y-%m-%dT%H:%MZ"),
        "To": t_to.strftime("%Y-%m-%dT%H:%MZ"),
        "format": "json",
    }
    r = None
    for attempt in range(retries):
        try:
            r = requests.get(url, params=params, timeout=60)
        except requests.RequestException:
            time.sleep(2 * (attempt + 1))
            continue
        if r.status_code == 200:
            return r.json().get("data", [])
        if r.status_code == 400:
            raise ValueError(r.text[:300])
        time.sleep(2 * (attempt + 1))
    raise RuntimeError(f"Failed after {retries} tries")

def find_window_days(probe_start="2024-03-01"):
    """
    Try longer windows first and return the longest one the server accepts.
    """
    t = pd.Timestamp(probe_start, tz="UTC")
    for days in [31, 14, 7, 3, 1]:
        try:
            t0 = time.perf_counter()
            fetch_window(t, t + pd.Timedelta(days=days))
            print(f"Window of {days} day(s) accepted ({time.perf_counter() - t0:.1f}s)")
            return days
        except ValueError:
            print(f"Window of {days} day(s) rejected")
    return 1


def download_one(t_from, t_to):
    """
    Download one window, using a cached file if it already exists.
    """
    path = os.path.join(cache_dir, f"{t_from:%Y%m%d}_{t_to:%Y%m%d}.csv")
    if os.path.exists(path):
        return pd.read_csv(path)
    df = pd.DataFrame(fetch_window(t_from, t_to))
    df.to_csv(path, index=False)
    return df


def main():
    os.makedirs(cache_dir, exist_ok=True)
    days = find_window_days()

    edges = pd.date_range(start, end, freq=f"{days}D", tz="UTC").tolist()
    if edges[-1] < pd.Timestamp(end, tz="UTC"):
        edges.append(pd.Timestamp(end, tz="UTC"))
    windows = list(zip(edges[:-1], edges[1:]))
    print(f"{len(windows)} windows of up to {days} day(s), {n_workers} in parallel")

    frames = []
    with ThreadPoolExecutor(max_workers=n_workers) as pool:
        futures = [pool.submit(download_one, a, b) for a, b in windows]
        for i, f in enumerate(as_completed(futures), 1):
            frames.append(f.result())
            if i % 25 == 0 or i == len(futures):
                print(f"  {i}/{len(futures)} windows done")

    df = pd.concat(frames, ignore_index=True)
    print(f"Downloaded {len(df)} raw rows")

    df = df[df["volume"] > 0]
    df = df[df["dataProvider"] == "APXMIDP"].copy()
    df["startTime"] = pd.to_datetime(df["startTime"], utc=True)
    df = df.drop_duplicates(subset="startTime").sort_values("startTime")
    df = df[["startTime", "settlementDate", "settlementPeriod", "price", "volume"]]

    df.to_csv(out_file, index=False)
    print(f"Saved {len(df)} half-hours to {out_file}")
    print("Half-hours per year (a full year has about 17,500):")
    print(df.groupby(df["startTime"].dt.year).size())
    print("Price summary (check the units against Elexon's documentation):")
    print(df["price"].describe())


if __name__ == "__main__":
    main()